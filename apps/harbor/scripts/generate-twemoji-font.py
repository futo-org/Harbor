# /// script
# requires-python = ">=3.11"
# dependencies = [
#   "nanoemoji",
#   "brotli",
#   # nanoemoji's CBDT build rasterizes with it.
#   "resvg-cli",
#   # nanoemoji needs these but doesn't declare them.
#   "ninja",
#   "typing_extensions",
# ]
# ///
#
# Writes the Twemoji SVGs as color fonts, which text draws emoji with:
# - `public/fonts/Twemoji-<hash>.woff2`: COLRv0, for web (see `app/+html.tsx`).
# - `src/common/assets/fonts/Twemoji.ttf`: the same, for iOS and Android 10+.
# - `src/common/assets/fonts/TwemojiCbdt.ttf`: bitmaps (CBDT), for Android 7-9,
#   which draw COLR glyphs blank.
# - `src/common/assets/twemojiFont.ts`: the web font's file name, and the space
#   around each glyph for the components that draw an emoji alone
#   (`EmojiImage`).
#
#   curl -L -o twemoji.tar.gz https://github.com/jdecked/twemoji/archive/refs/tags/v17.0.3.tar.gz
#   mkdir twemoji && tar -xzf twemoji.tar.gz -C twemoji --strip-components=1 '*/assets/svg/*'
#   pnpm -C apps/harbor generate:twemoji-font "$PWD/twemoji"
#
# Needs uv (e.g. `brew install uv`). A build takes about 20 minutes.
import hashlib
import os
import re
import subprocess
import sys
import tempfile
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from fontTools.feaLib.builder import addOpenTypeFeaturesFromString
from fontTools.otlLib.builder import LOOKUP_FLAG_IGNORE_MARKS
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.ttLib import TTFont
from fontTools.ttLib.tables._c_m_a_p import CmapSubtable

# The Twemoji README's `img.emoji` CSS, in font units: a 1em square, margins
# of 0.1em before and 0.05em after, 0.1em below the baseline.
UNITS_PER_EM = 1000
SPACE_BEFORE = 100
SPACE_AFTER = 50
BASELINE_SHIFT = 100

# The CBDT font's bitmap size in pixels, which larger emoji scale up from.
CBDT_BITMAP_SIZE = 96

# The Twemoji release's commit time (2026-06-01T22:16:04Z), as the fonts'
# creation and modification time, so rebuilding gives identical files.
TWEMOJI_RELEASE_TIME = 1780352164

# The Unicode version of the Twemoji release.
EMOJI_VARIATION_SEQUENCES_URL = 'https://www.unicode.org/Public/17.0.0/ucd/emoji/emoji-variation-sequences.txt'

app_dir = Path(__file__).resolve().parent.parent
web_font_dir = app_dir / 'public' / 'fonts'
native_font_file = app_dir / 'src' / 'common' / 'assets' / 'fonts' / 'Twemoji.ttf'
native_bitmap_font_file = app_dir / 'src' / 'common' / 'assets' / 'fonts' / 'TwemojiCbdt.ttf'
font_module_file = app_dir / 'src' / 'common' / 'assets' / 'twemojiFont.ts'


def main():
    # Read by fontTools here and in nanoemoji's build.
    os.environ['SOURCE_DATE_EPOCH'] = str(TWEMOJI_RELEASE_TIME)
    svg_dir = Path(sys.argv[1]).resolve() / 'assets' / 'svg'
    with tempfile.TemporaryDirectory() as build_dir:
        build_dir = Path(build_dir)
        stage_dir = stage_svgs(svg_dir, build_dir)
        with ThreadPoolExecutor() as executor:
            colr_file, cbdt_file = executor.map(
                lambda color_format: build_twemoji_font(stage_dir, build_dir / color_format, color_format),
                ['glyf_colr_0', 'cbdt'],
            )

        web_font = TTFont(colr_file)
        ignore_variation_selector(web_font)
        web_font.flavor = 'woff2'
        web_font.save(build_dir / 'Twemoji.woff2')
        web_font_name = publish_web_font(build_dir / 'Twemoji.woff2')

        emoji_style_bases = list_emoji_style_bases()
        for font_file, output_file in [(colr_file, native_font_file), (cbdt_file, native_bitmap_font_file)]:
            font = TTFont(font_file)
            ignore_variation_selector(font)
            declare_emoji_style_variants(font, emoji_style_bases)
            # iOS ships only the COLR font.
            if output_file == native_font_file:
                reserve_legacy_glyph_ids(font)
            font.save(output_file)

    write_font_module(web_font_name)


def publish_web_font(font_file):
    # Named by content: server.js caches it for a year without revalidating,
    # so a changed font needs a new URL.
    font_data = font_file.read_bytes()
    web_font_name = f'Twemoji-{hashlib.sha256(font_data).hexdigest()[:8]}.woff2'
    for old_font_file in web_font_dir.glob('Twemoji*.woff2'):
        old_font_file.unlink()
    (web_font_dir / web_font_name).write_bytes(font_data)
    return web_font_name


def write_font_module(web_font_name):
    font_module_file.write_text(f'''// Generated by scripts/generate-twemoji-font.py; do not edit.

/** The web font in public/fonts/. */
export const TWEMOJI_WEB_FONT_FILE = '{web_font_name}';

/** The space the Twemoji fonts leave before and after each glyph, in em. */
export const TWEMOJI_SPACE_BEFORE = {SPACE_BEFORE / UNITS_PER_EM};
export const TWEMOJI_SPACE_AFTER = {SPACE_AFTER / UNITS_PER_EM};
''')


def stage_svgs(svg_dir, build_dir):
    # Only some file names keep VS16 (`fe0f`); without it, every sequence is
    # keyed the same way (see `ignore_variation_selector`).
    stage_dir = build_dir / 'svg'
    stage_dir.mkdir()
    for svg in svg_dir.glob('*.svg'):
        (stage_dir / svg.name.replace('-fe0f', '')).write_text(make_view_box_square(svg.read_text()))
    return stage_dir


def build_twemoji_font(stage_dir, build_dir, color_format):
    # nanoemoji scales each viewBox to fill ascender to descender, centered in
    # the advance; the transform moves it off center. The CBDT build ignores
    # the transform, so its glyphs stay centered (0.075em on each side).
    subprocess.run(
        [
            sys.executable,
            '-m',
            'nanoemoji.nanoemoji',
            f'--color_format={color_format}',
            '--family=Twemoji',
            f'--upem={UNITS_PER_EM}',
            f'--ascender={UNITS_PER_EM - BASELINE_SHIFT}',
            f'--descender={-BASELINE_SHIFT}',
            f'--width={SPACE_BEFORE + UNITS_PER_EM + SPACE_AFTER}',
            f'--transform=matrix(1 0 0 1 {(SPACE_BEFORE - SPACE_AFTER) / 2} 0)',
            f'--build_dir={build_dir}',
            *([f'--bitmap_resolution={CBDT_BITMAP_SIZE}'] if color_format == 'cbdt' else []),
            '--output_file=Twemoji.ttf',
            *sorted(str(svg) for svg in stage_dir.iterdir()),
        ],
        check=True,
    )
    return build_dir / 'Twemoji.ttf'


# nanoemoji scales a viewBox's height to the glyph's, so the one SVG that
# isn't square (🍉, 36x25.22) came out 1.43em wide. Pads it like an `img`
# would show it: the short side centered.
def make_view_box_square(svg_text):
    match = re.search(r'viewBox="([^"]+)"', svg_text)
    x, y, width, height = map(float, match[1].split())
    size = max(width, height)
    view_box = f'{x - (size - width) / 2} {y - (size - height) / 2} {size} {size}'
    return svg_text.replace(match[0], f'viewBox="{view_box}"', 1)


# Matches sequences with or without VS16. Otherwise Chrome splits ZWJ
# sequences that contain it (🧍🏼‍♂️), and Safari breaks keycaps (1️⃣) and
# draws VS16 as a blank emoji-wide gap (❤️).
def ignore_variation_selector(font):
    font.setGlyphOrder([*font.getGlyphOrder(), 'uniFE0F'])
    font['glyf'].glyphs['uniFE0F'] = TTGlyphPen(None).glyph()
    font['glyf'].glyphOrder = font.getGlyphOrder()
    font['hmtx'].metrics['uniFE0F'] = (0, 0)
    for table in font['cmap'].tables:
        table.cmap[0xFE0F] = 'uniFE0F'
    # A mark, which the ligature lookups then skip.
    addOpenTypeFeaturesFromString(font, 'table GDEF { GlyphClassDef , , [uniFE0F], ; } GDEF;', tables={'GDEF'})
    for lookup in font['GSUB'].table.LookupList.Lookup:
        lookup.LookupFlag |= LOOKUP_FLAG_IGNORE_MARKS


# Android picks a font for an emoji with VS16 (❤️, 1️⃣, 🏳️‍🌈) only if the
# font declares that variant, otherwise the system emoji font draws it. A cmap
# 14 table declares it for every base Unicode lists. Web must not get it:
# WebKit then draws over a thousand VS16 sequences with Apple Color Emoji.
def declare_emoji_style_variants(font, emoji_style_bases):
    table = CmapSubtable.newSubtable(14)
    table.platformID = 0
    table.platEncID = 5
    table.language = 0xFF
    table.cmap = {}
    # Default variants: drawn with the glyph the base character maps to.
    table.uvsDict = {0xFE0F: [(code_point, None) for code_point in emoji_style_bases]}
    font['cmap'].tables.append(table)


# iOS text (TextKit 1, which React Native uses) drops format characters (tags,
# ZWJ) mapped to glyph IDs 1-3, the classic TrueType slots for `.null`,
# `nonmarkingreturn` and `space`. Tags of the UK flags sat at 2 and 3, so they
# drew as 🏴. Fills 2 and 3 with empty glyphs; `space` keeps 1.
def reserve_legacy_glyph_ids(font):
    # Every table refers to glyphs by name only once decompiled.
    font.ensureDecompiled()
    glyph_order = font.getGlyphOrder()
    font.setGlyphOrder([*glyph_order[:2], '.null', 'nonmarkingreturn', *glyph_order[2:]])
    font['glyf'].glyphOrder = font.getGlyphOrder()
    for name in ['.null', 'nonmarkingreturn']:
        font['glyf'].glyphs[name] = TTGlyphPen(None).glyph()
        font['hmtx'].metrics[name] = (0, 0)


def list_emoji_style_bases():
    with urllib.request.urlopen(EMOJI_VARIATION_SEQUENCES_URL) as response:
        lines = response.read().decode().splitlines()
    # e.g. `2764 FE0F  ; emoji style; # (1.1) HEAVY BLACK HEART`
    sequences = [line.split(';')[0].split() for line in lines if line and not line.startswith('#')]
    return sorted(int(base, 16) for base, selector in sequences if selector == 'FE0F')


main()
