// Writes the color scales to the app's `src/common/theme/palette.ts`.
//
// One scale per family, from light to dark, shared by both themes. All steps
// are evenly spaced in weight, so a step looks about equally strong anywhere on
// any scale. A hue family's scale is shifted by under half a step so that its
// key color is one of its steps. `colors.ts` picks each theme's colors from
// the scales.
import { writeFileSync } from 'node:fs';
import { clampChroma, converter, formatHex, wcagLuminance } from 'culori';

// Each hue family's scale has its key color as one of its steps; `primary`'s is
// the brand color. Neutral's only sets its hue and chroma.
const KEY_COLORS = {
  neutral: '#7C869D',
  primary: '#FF6A00',
  positive: '#34AE2F',
  negative: '#E34359',
  warning: '#FFA500',
};

// 0, 50, 100, ... 1000
const STEPS = Array.from({ length: 21 }, (_, index) => index * 50);

// OKLCH lightness of step 1000; `neutral_1000` is the dark theme's background.
const DARK_END_LIGHTNESS = 0.173;

// A color's weight is its luminance, raised for screen glare, to this power.
// Equal weight differences look about equally strong as dark on light and as
// light on dark, near white and near black.
const WEIGHT_EXPONENT = 0.6;

const outFile = new URL(
  '../../apps/harbor/src/common/theme/palette.ts',
  import.meta.url,
);

type Oklch = { mode: 'oklch'; l: number; c: number; h?: number };

const toOklch = converter('oklch');

const neutralKeyColor = parseColor(KEY_COLORS.neutral);
const darkEndWeight = getWeight(
  buildFamilyColor(neutralKeyColor, DARK_END_LIGHTNESS),
);

// one blank-line-separated group per family
const groups = [
  "  white: '#FFFFFF',\n  black: '#000000',",
  ...Object.entries(KEY_COLORS).map(([family, color]) =>
    formatScale(family, parseColor(color)),
  ),
];

writeFileSync(
  outFile,
  `// Generated by tools/palette (\`pnpm --filter @polycentric/palette generate\`).
// Do not edit.

export const palette = {\n${groups.join('\n\n')}\n};
`,
);

// The weight falls by a fixed amount per step, from white at step 0 to the dark
// end at step 1000. A hue family's steps are shifted to the nearest step to its
// key color's place.
function formatScale(family: string, keyColor: Oklch): string {
  const keyPlace = ((1 - getWeight(keyColor)) / (1 - darkEndWeight)) * 1000;
  const shift =
    family === 'neutral' ? 0 : keyPlace - Math.round(keyPlace / 50) * 50;
  return (
    STEPS
      // a hue family would only repeat white there
      .filter((step) => family === 'neutral' || step !== 0)
      .map((step) => {
        const weight = 1 - (1 - darkEndWeight) * ((step + shift) / 1000);
        const color = findFamilyColorByWeight(keyColor, weight);
        return `  ${family}_${step}: '${formatHex(color).toUpperCase()}',`;
      })
      .join('\n')
  );
}

// Weight rises with lightness, so a binary search finds the lightness.
function findFamilyColorByWeight(keyColor: Oklch, weight: number): Oklch {
  let low = 0;
  let high = 1;
  for (let iteration = 0; iteration < 50; iteration++) {
    const middle = (low + high) / 2;
    if (getWeight(buildFamilyColor(keyColor, middle)) < weight) low = middle;
    else high = middle;
  }
  return buildFamilyColor(keyColor, (low + high) / 2);
}

// The key color mixed toward white or black: its hue at the given lightness,
// with the chroma falling off evenly on both sides of the key's lightness.
function buildFamilyColor(keyColor: Oklch, lightness: number): Oklch {
  const chromaShare =
    lightness < keyColor.l
      ? lightness / keyColor.l
      : (1 - lightness) / (1 - keyColor.l);
  // lowers the chroma, at the same lightness and hue, until sRGB can show it
  return clampChroma(
    {
      mode: 'oklch',
      l: lightness,
      c: keyColor.c * chromaShare,
      h: keyColor.h,
    },
    'oklch',
  );
}

function getWeight(color: Oklch): number {
  const luminance = wcagLuminance(color);
  // APCA's soft clamp: glare on a real screen lifts the darkest colors
  const glareLuminance =
    luminance < 0.022
      ? luminance + (0.022 - luminance) ** Math.SQRT2
      : luminance;
  return glareLuminance ** WEIGHT_EXPONENT;
}

function parseColor(color: string): Oklch {
  const parsed = toOklch(color);
  if (!parsed) throw new Error(`Invalid color: ${color}`);
  return parsed;
}
