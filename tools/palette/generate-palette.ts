// Writes the color scales to the app's `src/common/theme/palette_new.ts`.
//
// Each theme gets its own scales. A step is a contrast level against the
// theme's background: 0 is the background, 1000 the strongest text, and the
// steps between are evenly spaced. Contrast is APCA's, which scores dark on
// light and light on dark differently, so a step is as strong in both themes.
// In a hue family step 500 is the family's key color in both themes, and the
// steps on each side are evenly spaced from there.
import { writeFileSync } from 'node:fs';
import { clampChroma, converter, formatHex } from 'culori';

// Step 500 of each hue family in both themes; `primary` is the brand color.
const KEY_COLORS = {
  primary: '#FF6A00',
  positive: '#34AE2F',
  negative: '#E34359',
  warning: '#FFA500',
};

// Supplies neutral's hue and chroma.
const NEUTRAL_COLOR = '#7C869D';

const STEPS = [0, 50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 1000];

// OKLCH lightness of the dark theme's background; the light theme's is white.
const DARK_BACKGROUND_LIGHTNESS = 0.173;

// OKLCH lightness of the light theme's strongest text, `neutral_1000`. The
// dark theme's is as strong against its own background.
const STRONGEST_TEXT_LIGHTNESS = 0.235;

const outFile = new URL(
  '../../apps/harbor/src/common/theme/palette_new.ts',
  import.meta.url,
);

type Oklch = { mode: 'oklch'; l: number; c: number; h?: number };

const toOklch = converter('oklch');
const toRgb = converter('rgb');

const neutral = parseColor(NEUTRAL_COLOR);

const strongestTextContrast = getContrast(
  buildFamilyColor(neutral, STRONGEST_TEXT_LIGHTNESS),
  buildFamilyColor(neutral, 1),
);

writeFileSync(
  outFile,
  `// Generated by tools/palette (\`pnpm --filter @polycentric/palette generate\`).
// Do not edit.

export const lightPalette = ${formatPalette(1)};

export const darkPalette: Palette = ${formatPalette(DARK_BACKGROUND_LIGHTNESS)};

export type Palette = typeof lightPalette;
`,
);

// one blank-line-separated group per family
function formatPalette(backgroundLightness: number): string {
  const background = buildFamilyColor(neutral, backgroundLightness);
  const groups = [
    "  white: '#FFFFFF',\n  black: '#000000',",
    formatScale(
      'neutral',
      neutral,
      background,
      // the even middle of the scale
      strongestTextContrast / 2,
    ),
    ...Object.entries(KEY_COLORS).map(([family, color]) => {
      const keyColor = parseColor(color);
      return formatScale(
        family,
        keyColor,
        background,
        getContrast(keyColor, background),
      );
    }),
  ];
  return `{\n${groups.join('\n\n')}\n}`;
}

// The contrast changes by a fixed amount per step: one amount from the
// background up to the middle contrast at step 500, another from there to the
// strongest text at step 1000.
function formatScale(
  family: string,
  keyColor: Oklch,
  background: Oklch,
  middleContrast: number,
): string {
  return (
    STEPS
      // a hue family would only repeat the background there
      .filter((step) => family === 'neutral' || step !== 0)
      .map((step) => {
        const contrast =
          step <= 500
            ? middleContrast * (step / 500)
            : middleContrast +
              (strongestTextContrast - middleContrast) * ((step - 500) / 500);
        const color =
          step === 0 ? background : findColor(keyColor, background, contrast);
        return `  ${family}_${step}: '${formatHex(color).toUpperCase()}',`;
      })
      .join('\n')
  );
}

// The family's color with the given contrast against the background.
function findColor(
  keyColor: Oklch,
  background: Oklch,
  contrast: number,
): Oklch {
  // colors get darker away from a light background, lighter from a dark one
  let weakerLightness = background.l;
  let strongerLightness = background.l > 0.5 ? 0 : 1;
  for (let iteration = 0; iteration < 50; iteration++) {
    const lightness = (weakerLightness + strongerLightness) / 2;
    if (
      getContrast(buildFamilyColor(keyColor, lightness), background) < contrast
    ) {
      weakerLightness = lightness;
    } else {
      strongerLightness = lightness;
    }
  }
  return buildFamilyColor(keyColor, strongerLightness);
}

// The key color mixed toward white or black: its hue at the given lightness,
// with the chroma falling off evenly on both sides of the key's lightness.
function buildFamilyColor(keyColor: Oklch, lightness: number): Oklch {
  const chromaShare =
    lightness < keyColor.l
      ? lightness / keyColor.l
      : (1 - lightness) / (1 - keyColor.l);
  // lowers the chroma, at the same lightness and hue, until sRGB can show it
  return clampChroma(
    {
      mode: 'oklch',
      l: lightness,
      c: keyColor.c * chromaShare,
      h: keyColor.h,
    },
    'oklch',
  );
}

// APCA's contrast between a text color and its background, without the offset,
// low-contrast cutoff and black clamp of its Lc score, so it stays even down to
// the background. The exponents differ for dark text on a light background and
// the reverse.
function getContrast(text: Oklch, background: Oklch): number {
  const textLuminance = getLuminance(text);
  const backgroundLuminance = getLuminance(background);
  return backgroundLuminance > textLuminance
    ? (backgroundLuminance ** 0.56 - textLuminance ** 0.57) * 114
    : (textLuminance ** 0.62 - backgroundLuminance ** 0.65) * 114;
}

// APCA's luminance: a plain 2.4 gamma instead of the sRGB curve.
function getLuminance(color: Oklch): number {
  const { r, g, b } = toRgb(color);
  return 0.2126729 * r ** 2.4 + 0.7151522 * g ** 2.4 + 0.072175 * b ** 2.4;
}

function parseColor(color: string): Oklch {
  const parsed = toOklch(color);
  if (!parsed) throw new Error(`Invalid color: ${color}`);
  return parsed;
}
