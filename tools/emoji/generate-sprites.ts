// Builds the Android picker's sprite pages from the Twemoji 72px PNGs, for
// the emoji-sprite module, which decodes a page only once one of its emoji is
// shown, and writes their layout to the app's `src/common/emoji/sheet.ts`.
// Elsewhere emoji are drawn with the Twemoji font (generate-font.py). See
// README.md.

import { existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import versions from './versions.json' with { type: 'json' };
import { listUnicodeEmojis } from './shared/listUnicodeEmojis.ts';

const app = fileURLToPath(new URL('../../apps/harbor/', import.meta.url));
const twemoji = fileURLToPath(
  new URL(`downloads/twemoji/${versions.twemoji}/`, import.meta.url),
);
const emojiDir = `${app}src/common/emoji/`;
const pngs = `${twemoji}assets/72x72/`;

const CELL = 72;
// Android sprite pages: up to 16x17 cells of 72px, about 5.6 MB per decoded
// page; 17 rows fit the 264- and 270-emoji categories without a near-empty
// overflow page.
const PAGE_COLUMNS = 16;
const PAGE_CELLS = PAGE_COLUMNS * 17;
const pagesDir = `${app}modules/emoji-sprite/android/src/main/assets/emoji-sprite/`;

const sheetEmojis: string[] = [];
const sheetFiles: string[] = [];
const sheetCategories: string[] = [];
for (const { emoji, category } of listUnicodeEmojis(versions.unicode.picker)) {
  const code = [...emoji]
    .map((character) => character.codePointAt(0)?.toString(16))
    .join('-');
  // Twemoji drops U+FE0F from file names, except in ZWJ sequences other than
  // 👁️‍🗨️ (1f441-200d-1f5e8).
  const file = [`${code}.png`, `${code.replaceAll('-fe0f', '')}.png`].find(
    (name) => existsSync(`${pngs}${name}`),
  );
  if (file) {
    sheetEmojis.push(emoji);
    sheetFiles.push(file);
    sheetCategories.push(category);
  } else console.warn(`no twemoji for ${emoji} (${code})`);
}

// Sheet index of the first emoji on each Android page. Every category starts
// a new page, so the top of a category (what the picker shows first after a
// category switch) is always on a single page.
const pageStarts: number[] = [];
for (let i = 0; i < sheetEmojis.length; i++) {
  const pageStart = pageStarts.at(-1);
  if (
    pageStart === undefined ||
    sheetCategories[i] !== sheetCategories[i - 1] ||
    i - pageStart === PAGE_CELLS
  )
    pageStarts.push(i);
}
// Escaped so that ZWJs, U+FE0F and tag characters show in the file.
const escapeEmoji = (emoji: string) =>
  [...emoji]
    .map(
      (character) =>
        `\\u{${character.codePointAt(0)?.toString(16).toUpperCase()}}`,
    )
    .join('');
writeFileSync(
  `${emojiDir}sheet.ts`,
  `// Generated by tools/emoji/generate-sprites.ts; do not edit.

/** Sheet index of the first emoji on each Android sprite page
 * (emoji-sprite module); a page holds the emoji up to the next start. */
export const SPRITE_PAGE_STARTS = [${pageStarts.join(', ')}];

/** Cells per row of an Android sprite page. */
export const SPRITE_PAGE_COLUMNS = ${PAGE_COLUMNS};

/** The emoji on the sprite pages, in sheet order, as in \`emojis.json\`. */
export const SPRITE_EMOJIS = [${sheetEmojis.map((emoji) => `'${escapeEmoji(emoji)}'`).join(', ')}];
`,
);

rmSync(pagesDir, { recursive: true, force: true });
mkdirSync(pagesDir, { recursive: true });
for (let page = 0; page < pageStarts.length; page++) {
  const pageFiles = sheetFiles.slice(pageStarts[page], pageStarts[page + 1]);
  const pagePng = await sharp({
    create: {
      width: CELL * PAGE_COLUMNS,
      height: CELL * Math.ceil(pageFiles.length / PAGE_COLUMNS),
      channels: 4,
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    },
  })
    .composite(
      pageFiles.map((file, i) => ({
        input: `${pngs}${file}`,
        left: (i % PAGE_COLUMNS) * CELL,
        top: Math.floor(i / PAGE_COLUMNS) * CELL,
      })),
    )
    .png({ compressionLevel: 9, palette: false })
    .toBuffer();
  writeFileSync(`${pagesDir}page-${page}.png`, pagePng);
}
console.log(
  `${sheetEmojis.length} emoji -> ${pageStarts.length} Android sprite pages in modules/emoji-sprite`,
);
