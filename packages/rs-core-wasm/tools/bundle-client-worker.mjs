// Bundle src/client-worker.ts into one self-contained script and emit it
// as a string module. The page starts the worker from a Blob URL, so it
// works with any bundler (Metro included) and needs no extra asset; the
// wasm URL is passed to the worker in its first message.
import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';

const result = await build({
  entryPoints: ['src/client-worker.ts'],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  write: false,
  // `@ubjs/wasm` picks its browser build through export conditions.
  conditions: ['browser', 'import', 'default'],
  logLevel: 'warning',
});

const source = result.outputFiles[0].text;
await writeFile(
  'src/generated/client-worker-source.ts',
  `// Generated by tools/bundle-client-worker.mjs. Do not edit.\nexport const CLIENT_WORKER_SOURCE: string = ${JSON.stringify(source)};\n`,
);
console.log(`client worker: ${(source.length / 1024).toFixed(0)} KiB`);
